-- PRヘッダーの合計金額も明細合計に合わせる場合
update purchase_request pr
set total_amount_excluding_tax = detail.total
from (
  select
    pr_id,
    sum(subtotal_excluding_tax) as total
  from purchase_request_detail
  group by pr_id
) detail
where pr.pr_id = detail.pr_id;
